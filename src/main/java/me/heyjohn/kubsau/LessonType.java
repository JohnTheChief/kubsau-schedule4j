package me.heyjohn.kubsau;

/**
 * Тип занятия. Сайт выделяет только лекции (жирным шрифтом и классом {@code lection yes});
 * всё остальное (практики, лабораторные, семинары) отдаётся без пометки.
 */
public enum LessonType {
    /** Лекция. */
    LECTURE,
    /** Практическое, лабораторное или иное занятие, не помеченное сайтом как лекция. */
    PRACTICE
}
